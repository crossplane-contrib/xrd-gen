func TestYAMLSerializer_SerializeXRD(t *testing.T) {
	xrd := &domain.CompositeResourceDefinition{
		Name:       "xmydbs.example.com",
		Group:      "example.com",
		Version:    "v1alpha1",
		Kind:       "XMyDB",
		PluralName: "xmydbs",
		Schema: &domain.OpenAPISchema{
			Type: "object",
			Properties: map[string]*domain.OpenAPISchema{
				"spec": {
					Type: "object",
					Properties: map[string]*domain.OpenAPISchema{
						"version": {
							Type:        "string",
							Description: "Version of the database engine.",
						},
						"count": {
							Type:        "integer",
							Description: "Number of nodes.",
						},
					},
					Required: []string{"version"},
				},
			},
		},
	}

	data, err := SerializeXRD(xrd)
	require.NoError(t, err)
	require.NotEmpty(t, data)

	expectedYAML := `# Code generated by xrd-gen ` + version.Version + `. DO NOT EDIT.
apiVersion: apiextensions.crossplane.io/v2
kind: CompositeResourceDefinition
metadata:
  name: xmydbs.example.com
  annotations:
    xrd-gen.crossplane.io/version: ` + version.Version + `
spec:
  group: example.com
  names:
    kind: XMyDB
    plural: xmydbs
  versions:
    - name: v1alpha1
      served: true
      referenceable: true
      schema:
        openAPIV3Schema:
          type: object
          properties:
            spec:
              type: object
              properties:
                version:
                  type: string
                  description: Version of the database engine.
                count:
                  type: integer
                  description: Number of nodes.
              required:
                - version
`

	require.YAMLEq(t, expectedYAML, string(data))
}

