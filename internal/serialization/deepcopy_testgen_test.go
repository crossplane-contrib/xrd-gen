func TestGenerateDeepCopyTests_Empty(t *testing.T) {
	result, err := GenerateDeepCopyTests(nil, "")
	require.NoError(t, err)
	require.Empty(t, result)
}

func TestGenerateDeepCopyTests_SingleStruct(t *testing.T) {
	structs := []parsing.Struct{
		{
			Name:    "SimpleType",
			Package: "testpkg",
		},
	}

	code, err := GenerateDeepCopyTests(structs, "")
	require.NoError(t, err)

	codeStr := string(code)
	require.Contains(t, codeStr, "package testpkg")
	require.Contains(t, codeStr, "func TestDeepCopy_SimpleType(t *testing.T)")
	require.Contains(t, codeStr, "original := &SimpleType{}")
	require.Contains(t, codeStr, "copy := original.DeepCopy()")
	require.Contains(t, codeStr, "if original == copy")
	require.Contains(t, codeStr, "func TestDeepCopy_SimpleType_Nil(t *testing.T)")
}

func TestGenerateDeepCopyTests_WithTypeMeta(t *testing.T) {
	structs := []parsing.Struct{
		{
			Name:    "MyResource",
			Package: "testpkg",
			Fields: []parsing.Field{
				{
					Name:     "",
					IsInline: true,
					Type: parsing.MetadataType{
						Name:       "TypeMeta",
						Package:    "metav1",
						ImportPath: "k8s.io/apimachinery/pkg/apis/meta/v1",
					},
				},
			},
		},
	}

	code, err := GenerateDeepCopyTests(structs, "")
	require.NoError(t, err)

	codeStr := string(code)
	require.Contains(t, codeStr, "func TestDeepCopy_MyResource(t *testing.T)")
	require.Contains(t, codeStr, "func TestDeepCopyObject_MyResource(t *testing.T)")
	require.Contains(t, codeStr, "func TestDeepCopyObject_MyResource_Nil(t *testing.T)")
	require.Contains(t, codeStr, "DeepCopyObject()")
}

func TestGenerateDeepCopyTests_ComprehensiveCodeCheck(t *testing.T) {
	structs := []parsing.Struct{
		{
			Name:    "ComplexType",
			Package: "testpkg",
			Fields: []parsing.Field{
				{
					Name:     "",
					IsInline: true,
					Type: parsing.MetadataType{
						Name:       "TypeMeta",
						Package:    "metav1",
						ImportPath: "k8s.io/apimachinery/pkg/apis/meta/v1",
					},
				},
				{
					Name: "StringValue",
					Type: parsing.StringType{IsPointer: false},
				},
				{
					Name: "NumberValue",
					Type: parsing.NumericType{Name: "int32", IsPointer: false},
				},
				{
					Name: "StringArray",
					Type: parsing.ArrayType{
						ElementType: parsing.StringType{IsPointer: false},
					},
				},
				{
					Name: "StringMap",
					Type: parsing.MapType{
						KeyType:   parsing.StringType{IsPointer: false},
						ValueType: parsing.StringType{IsPointer: false},
					},
				},
			},
		},
		{
			Name:    "SimpleType",
			Package: "testpkg",
			Fields: []parsing.Field{
				{
					Name: "Name",
					Type: parsing.StringType{IsPointer: false},
				},
			},
		},
	}

	result, err := GenerateDeepCopyTests(structs, "")
	require.NoError(t, err)

	expectedCode := `//go:build !ignore_autogenerated

// Code generated by xrd-gen ` + version.Version + `. DO NOT EDIT.

package testpkg

import "testing"

func TestDeepCopy_ComplexType(t *testing.T) {
	original := &ComplexType{}

	copy := original.DeepCopy()

	if copy == nil {
		t.Fatal("DeepCopy() returned nil")
	}

	if original == copy {
		t.Error("DeepCopy() returned the same pointer")
	}
}

func TestDeepCopy_ComplexType_Nil(t *testing.T) {
	var original *ComplexType
	copy := original.DeepCopy()
	if copy != nil {
		t.Error("DeepCopy() on nil should return nil")
	}
}

func TestDeepCopyObject_ComplexType(t *testing.T) {
	original := &ComplexType{}

	obj := original.DeepCopyObject()
	if obj == nil {
		t.Fatal("DeepCopyObject() returned nil")
	}

	copy, ok := obj.(*ComplexType)
	if !ok {
		t.Fatalf("DeepCopyObject() returned wrong type: %T", obj)
	}

	if original == copy {
		t.Error("DeepCopyObject() returned the same pointer")
	}
}

func TestDeepCopyObject_ComplexType_Nil(t *testing.T) {
	var original *ComplexType
	obj := original.DeepCopyObject()
	if obj != nil {
		t.Error("DeepCopyObject() on nil should return nil")
	}
}

func TestDeepCopy_SimpleType(t *testing.T) {
	original := &SimpleType{}

	copy := original.DeepCopy()

	if copy == nil {
		t.Fatal("DeepCopy() returned nil")
	}

	if original == copy {
		t.Error("DeepCopy() returned the same pointer")
	}
}

func TestDeepCopy_SimpleType_Nil(t *testing.T) {
	var original *SimpleType
	copy := original.DeepCopy()
	if copy != nil {
		t.Error("DeepCopy() on nil should return nil")
	}
}
`

	requireCodeEquals(t, expectedCode, string(result))
}
