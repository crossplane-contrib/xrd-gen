package serialization

import (
	"encoding/json"
	"fmt"
	"maps"
	"sort"

	xpv2 "github.com/crossplane/crossplane/apis/v2/apiextensions/v2"
	extv1 "k8s.io/apiextensions-apiserver/pkg/apis/apiextensions/v1"
	metav1 "k8s.io/apimachinery/pkg/apis/meta/v1"
	"k8s.io/apimachinery/pkg/runtime"
	"sigs.k8s.io/yaml"

	"github.com/crossplane-contrib/xrd-gen/internal/domain"
	"github.com/crossplane-contrib/xrd-gen/pkg/version"
)

func SerializeXRD(xrd *domain.CompositeResourceDefinition) ([]byte, error) {
	// Convert to official Crossplane v2 type
	xrdObj, err := convertToXPv2(xrd)
	if err != nil {
		return nil, fmt.Errorf("failed to convert to Crossplane v2 type: %w", err)
	}

	// Marshal to YAML and remove empty status field
	yamlBytes, err := marshalAndCleanXRD(xrdObj)
	if err != nil {
		return nil, err
	}

	// Add autogenerated header comment
	header := fmt.Sprintf("# Code generated by xrd-gen %s. DO NOT EDIT.\n", version.Version)
	return append([]byte(header), yamlBytes...), nil
}

func marshalAndCleanXRD(xrdObj *xpv2.CompositeResourceDefinition) ([]byte, error) {
	// Marshal to JSON first, since Crossplane types have omitempty tags only for JSON.
	jsonBytes, err := json.Marshal(xrdObj)
	if err != nil {
		return nil, fmt.Errorf("failed to marshal XRD to JSON: %w", err)
	}

	// Unmarshal to map to strip empty fields and remove the status field
	var doc map[string]any
	if err := json.Unmarshal(jsonBytes, &doc); err != nil {
		return nil, fmt.Errorf("failed to unmarshal JSON: %w", err)
	}
	delete(doc, "status") // status is only set by Crossplane, so we don't need to include it in the XRD.

	// Convert the cleaned map directly to YAML
	yamlBytes, err := yaml.Marshal(doc)
	if err != nil {
		return nil, fmt.Errorf("failed to marshal cleaned YAML: %w", err)
	}

	return yamlBytes, nil
}

func convertToXPv2(xrd *domain.CompositeResourceDefinition) (*xpv2.CompositeResourceDefinition, error) {
	schemaJSON, err := convertSchemaToJSON(xrd.Schema)
	if err != nil {
		return nil, fmt.Errorf("failed to convert schema: %w", err)
	}

	served := true
	referenceable := true

	additionalPrinterColumns := make([]extv1.CustomResourceColumnDefinition, 0, len(xrd.AdditionalPrinterColumns))
	for _, col := range xrd.AdditionalPrinterColumns {
		additionalPrinterColumns = append(additionalPrinterColumns, extv1.CustomResourceColumnDefinition{
			Name:        col.Name,
			Type:        col.Type,
			JSONPath:    col.JSONPath,
			Description: col.Description,
			Priority:    col.Priority,
		})
	}

	annotations := make(map[string]string)
	maps.Copy(annotations, xrd.Annotations)
	annotations["xrd-gen.crossplane.io/version"] = version.Version

	labels := make(map[string]string)
	maps.Copy(labels, xrd.Labels)

	return &xpv2.CompositeResourceDefinition{
		TypeMeta: metav1.TypeMeta{
			APIVersion: "apiextensions.crossplane.io/v2",
			Kind:       "CompositeResourceDefinition",
		},
		ObjectMeta: metav1.ObjectMeta{
			Name:        xrd.Name,
			Labels:      labels,
			Annotations: annotations,
		},
		Spec: xpv2.CompositeResourceDefinitionSpec{
			Group: xrd.Group,
			Names: extv1.CustomResourceDefinitionNames{
				Kind:   xrd.Kind,
				Plural: xrd.PluralName,
			},
			Versions: []xpv2.CompositeResourceDefinitionVersion{
				{
					Name:                     xrd.Version,
					Served:                   served,
					Referenceable:            referenceable,
					AdditionalPrinterColumns: additionalPrinterColumns,
					Schema: &xpv2.CompositeResourceValidation{
						OpenAPIV3Schema: runtime.RawExtension{
							Raw: schemaJSON,
						},
					},
				},
			},
		},
	}, nil
}

func convertSchemaToJSON(schema *domain.OpenAPISchema) ([]byte, error) {
	props, err := convertToJSONSchemaProps(schema)
	if err != nil {
		return nil, err
	}
	sortRequiredFields(props)
	return json.Marshal(props)
}

func convertToJSONSchemaProps(schema *domain.OpenAPISchema) (*extv1.JSONSchemaProps, error) {
	if schema == nil {
		return nil, nil
	}

	props := &extv1.JSONSchemaProps{
		Type:        schema.Type,
		Description: schema.Description,
	}

	if len(schema.Properties) > 0 {
		props.Properties = make(map[string]extv1.JSONSchemaProps, len(schema.Properties))
		for name, propSchema := range schema.Properties {
			prop, err := convertToJSONSchemaProps(propSchema)
			if err != nil {
				return nil, err
			}
			props.Properties[name] = *prop
		}
	}

	if len(schema.Required) > 0 {
		props.Required = make([]string, len(schema.Required))
		copy(props.Required, schema.Required)
	}

	if schema.Items != nil {
		items, err := convertToJSONSchemaProps(schema.Items)
		if err != nil {
			return nil, err
		}
		props.Items = &extv1.JSONSchemaPropsOrArray{
			Schema: items,
		}
	}

	if schema.AdditionalProperties != nil {
		additionalProps, err := convertToJSONSchemaProps(schema.AdditionalProperties)
		if err != nil {
			return nil, err
		}
		props.AdditionalProperties = &extv1.JSONSchemaPropsOrBool{
			Schema: additionalProps,
		}
	}

	if schema.MinItems != nil {
		minItems := int64(*schema.MinItems)
		props.MinItems = &minItems
	}

	if schema.MaxItems != nil {
		maxItems := int64(*schema.MaxItems)
		props.MaxItems = &maxItems
	}

	if schema.MinLength != nil {
		minLength := int64(*schema.MinLength)
		props.MinLength = &minLength
	}

	if schema.MaxLength != nil {
		maxLength := int64(*schema.MaxLength)
		props.MaxLength = &maxLength
	}

	if schema.Minimum != nil {
		props.Minimum = schema.Minimum
	}

	if schema.Maximum != nil {
		props.Maximum = schema.Maximum
	}

	if schema.Pattern != nil {
		props.Pattern = *schema.Pattern
	}

	if schema.Format != nil {
		props.Format = *schema.Format
	}

	if len(schema.Enum) > 0 {
		props.Enum = make([]extv1.JSON, len(schema.Enum))
		for i, val := range schema.Enum {
			jsonVal, err := json.Marshal(val)
			if err != nil {
				return nil, fmt.Errorf("failed to marshal enum value %s: %w", val, err)
			}
			props.Enum[i] = extv1.JSON{Raw: jsonVal}
		}
	}

	if schema.Default != nil {
		jsonVal, err := json.Marshal(schema.Default)
		if err != nil {
			return nil, fmt.Errorf("failed to marshal default value: %w", err)
		}
		props.Default = &extv1.JSON{Raw: jsonVal}
	}

	if len(schema.XValidations) > 0 {
		for _, xv := range schema.XValidations {
			rule := extv1.ValidationRule{
				Rule:              xv.Rule,
				Message:           xv.Message,
				MessageExpression: xv.MessageExpression,
				FieldPath:         xv.FieldPath,
				OptionalOldSelf:   xv.OptionalOldSelf,
			}
			if xv.Reason != "" {
				reason := extv1.FieldValueErrorReason(xv.Reason)
				rule.Reason = &reason
			}
			props.XValidations = append(props.XValidations, rule)
		}
	}

	return props, nil
}

// sortRequiredFields recursively sorts all Required arrays in the schema for deterministic output
func sortRequiredFields(props *extv1.JSONSchemaProps) {
	if props == nil || props.Required == nil {
		return
	}

	// Sort the required array at the current level
	sort.Strings(props.Required)

	// Recursively sort required arrays in properties
	// We need to create a new map and copy the sorted properties because
	// we can't modify struct values in a map directly
	if len(props.Properties) > 0 {
		sortedProps := make(map[string]extv1.JSONSchemaProps, len(props.Properties))
		for key, prop := range props.Properties {
			propCopy := prop
			sortRequiredFields(&propCopy)
			sortedProps[key] = propCopy
		}
		props.Properties = sortedProps
	}

	if props.Items != nil && props.Items.Schema != nil {
		sortRequiredFields(props.Items.Schema)
	}

	if props.AdditionalProperties != nil && props.AdditionalProperties.Schema != nil {
		sortRequiredFields(props.AdditionalProperties.Schema)
	}
}
