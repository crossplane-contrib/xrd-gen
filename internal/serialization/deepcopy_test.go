func TestGenerateDeepCopy_AlphabeticalOrdering(t *testing.T) {
	structs := []parsing.Struct{
		{Name: "Zebra", Package: "testpkg"},
		{Name: "Alpha", Package: "testpkg"},
		{Name: "Beta", Package: "testpkg"},
	}

	result, err := GenerateDeepCopy(structs, "")
	require.NoError(t, err)

	code := string(result)

	// Find positions of each struct's DeepCopyInto method
	alphaPos := strings.Index(code, "func (in *Alpha) DeepCopyInto")
	betaPos := strings.Index(code, "func (in *Beta) DeepCopyInto")
	zebraPos := strings.Index(code, "func (in *Zebra) DeepCopyInto")

	require.NotEqual(t, -1, alphaPos, "Alpha should be present")
	require.NotEqual(t, -1, betaPos, "Beta should be present")
	require.NotEqual(t, -1, zebraPos, "Zebra should be present")

	// Verify alphabetical order
	require.Less(t, alphaPos, betaPos, "Alpha should come before Beta")
	require.Less(t, betaPos, zebraPos, "Beta should come before Zebra")
}

