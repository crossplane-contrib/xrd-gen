package files

import (
	"os"
	"path/filepath"
	"testing"

	"github.com/stretchr/testify/require"

	"github.com/crossplane-contrib/xrd-gen/internal/domain"
)

func TestFileWriter_WriteXRDYAML(t *testing.T) {
	tempDir := t.TempDir()
	writer := NewFileWriter(tempDir)

	xrd := &domain.CompositeResourceDefinition{
		Name:       "xmydbs.example.com",
		Kind:       "XMyDB",
		PluralName: "xmydbs",
	}

	yamlData := []byte("apiVersion: apiextensions.crossplane.io/v2\nkind: CompositeResourceDefinition\n")

	err := writer.WriteXRDYAML(xrd, yamlData)
	require.NoError(t, err)

	yamlFilePath := filepath.Join(tempDir, "xmydb.yaml")
	require.FileExists(t, yamlFilePath)

	content, err := os.ReadFile(yamlFilePath)
	require.NoError(t, err)
	require.Equal(t, yamlData, content)
}

func TestFileWriter_WriteDeepCopyGo(t *testing.T) {
	tempDir := t.TempDir()
	writer := NewFileWriter(tempDir)

	goCode := []byte("// Code generated by xrd-gen. DO NOT EDIT.\n\npackage v1\n")

	err := writer.WriteDeepCopyGo(tempDir, goCode)
	require.NoError(t, err)

	goFilePath := filepath.Join(tempDir, "zz_generated.deepcopy.go")
	require.FileExists(t, goFilePath)

	content, err := os.ReadFile(goFilePath)
	require.NoError(t, err)
	require.Equal(t, goCode, content)
}

func TestFileWriter_WriteXRDYAML_CreatesDirectory(t *testing.T) {
	tempDir := t.TempDir()
	outputDir := filepath.Join(tempDir, "output")
	writer := NewFileWriter(outputDir)

	xrd := &domain.CompositeResourceDefinition{
		Kind: "XTest",
	}

	yamlData := []byte("test: data\n")

	err := writer.WriteXRDYAML(xrd, yamlData)
	require.NoError(t, err)

	info, err := os.Stat(outputDir)
	require.NoError(t, err)
	require.True(t, info.IsDir())

	yamlFilePath := filepath.Join(outputDir, "xtest.yaml")
	require.FileExists(t, yamlFilePath)
}
